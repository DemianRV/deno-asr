/**
 * deno run -A scripts/install_linux.ts <install|uninstall> [flags]
 *
 * Per-user install (no sudo) of the `deno desktop` build into ~/.local:
 * app copy, launcher with log file, menu entry + icon, autostart, `deno-asr` on PATH.
 * Config and dataset are never touched.
 */
import { dirname, join } from "@std/path";
import { buildLinux } from "./build.ts";
import { configDir } from "../src/core/config.ts";
import { sendControl, socketPath } from "../src/core/control.ts";
import { isWayland } from "../src/core/platform/linux.ts";
import { appIcon } from "../src/desktop/icons.ts";

const ROOT = new URL("..", import.meta.url).pathname;
const DIST = join(ROOT, "dist/deno-asr");
export const APP_ID = "dev.damian.deno-asr";

export interface InstallPaths {
  /** Holds `app/` and the launcher script. */
  dataDir: string;
  appDir: string;
  appNew: string;
  appOld: string;
  exe: string;
  launcher: string;
  bin: string;
  desktop: string;
  autostart: string;
  icon: string;
  stateDir: string;
  log: string;
}

type Env = Pick<typeof Deno.env, "get">;

export function installPaths(home: string, env: Env = { get: () => undefined }): InstallPaths {
  const data = env.get("XDG_DATA_HOME") || join(home, ".local/share");
  const config = env.get("XDG_CONFIG_HOME") || join(home, ".config");
  const state = env.get("XDG_STATE_HOME") || join(home, ".local/state");
  const dataDir = join(data, "deno-asr");
  const appDir = join(dataDir, "app");
  const stateDir = join(state, "deno-asr");
  return {
    dataDir,
    appDir,
    appNew: `${appDir}.new`,
    appOld: `${appDir}.old`,
    exe: join(appDir, "deno-asr"),
    launcher: join(dataDir, "deno-asr-launch"),
    bin: join(home, ".local/bin/deno-asr"),
    desktop: join(data, "applications", `${APP_ID}.desktop`),
    autostart: join(config, "autostart", `${APP_ID}.desktop`),
    icon: join(data, "icons/hicolor/256x256/apps", `${APP_ID}.png`),
    stateDir,
    log: join(stateDir, "app.log"),
  };
}

/** POSIX shell single-quoting. */
export function shq(s: string): string {
  return `'${s.replaceAll("'", `'\\''`)}'`;
}

/** Launcher run by the menu entry: GNOME discards app output, so send it to a log file. */
export function launcherScript(p: InstallPaths, debug: boolean): string {
  return [
    "#!/bin/sh",
    "# Generated by scripts/install_linux.ts. Re-run the installer instead of editing.",
    `mkdir -p ${shq(p.stateDir)}`,
    ...(debug ? ["export ASR_DEBUG='*'"] : []),
    `printf '\\n=== %s start ===\\n' "$(date -Is)" >>${shq(p.log)}`,
    `exec ${shq(p.exe)} "$@" >>${shq(p.log)} 2>&1`,
    "",
  ].join("\n");
}

/** Quotes an Exec argument per the Desktop Entry spec (quoting + string-value escaping). */
export function desktopExecArg(arg: string): string {
  if (!/[\s"'\\$`<>~|&;*?#()%]/.test(arg)) return arg;
  const quoted = arg.replace(/[\\"`$]/g, "\\$&").replaceAll("%", "%%");
  // Desktop string values unescape `\\` once more, so double every backslash.
  return `"${quoted.replaceAll("\\", "\\\\")}"`;
}

export function desktopEntry(opts: { launcher: string; autostart: boolean }): string {
  const lines = [
    "[Desktop Entry]",
    "Type=Application",
    "Name=Deno ASR",
    "Comment=Dictado por voz con atajo global",
    `Exec=${desktopExecArg(opts.launcher)}`,
    `Icon=${APP_ID}`,
    `StartupWMClass=${APP_ID}`,
    "Categories=Utility;",
    "Terminal=false",
  ];
  if (opts.autostart) {
    // Give the AppIndicator extension time to load, or the tray icon can't be created.
    lines.push("X-GNOME-Autostart-enabled=true", "X-GNOME-Autostart-Delay=5");
  }
  return lines.join("\n") + "\n";
}

export const REQUIRED_PACKAGES = [
  "xclip",
  "xdotool",
  "wl-clipboard",
  "zenity",
  "libnotify-bin",
  "netcat-openbsd",
  "libwebkit2gtk-4.1-0",
  "libayatana-appindicator3-1",
];
export const TRAY_EXTENSION = "gnome-shell-extension-appindicator";

/** `statusOf(pkg)` returns dpkg's status string, or null if unknown. */
export async function missingPackages(
  statusOf: (pkg: string) => Promise<string | null>,
  wayland: boolean,
): Promise<{ missing: string[]; trayExtension: boolean }> {
  const installed = async (pkg: string) => (await statusOf(pkg))?.includes("ok installed") ?? false;
  const wanted = wayland ? [...REQUIRED_PACKAGES, "ydotool"] : REQUIRED_PACKAGES;
  const missing: string[] = [];
  for (const pkg of wanted) if (!(await installed(pkg))) missing.push(pkg);
  return { missing, trayExtension: await installed(TRAY_EXTENSION) };
}

